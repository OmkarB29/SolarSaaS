package com.mpc.model3d.service;

import com.fasterxml.jackson.databind.JsonNode;
import com.fasterxml.jackson.databind.ObjectMapper;
import com.fasterxml.jackson.databind.node.ArrayNode;
import com.fasterxml.jackson.databind.node.ObjectNode;
import com.mpc.model3d.config.MeshyModel3DProperties;
import org.slf4j.Logger;
import org.slf4j.LoggerFactory;
import org.springframework.http.*;
import org.springframework.stereotype.Service;
import org.springframework.web.client.HttpClientErrorException;
import org.springframework.web.client.ResourceAccessException;
import org.springframework.web.client.RestTemplate;

@Service
public class MeshyClient {

    private static final Logger log = LoggerFactory.getLogger(MeshyClient.class);

    private final MeshyModel3DProperties properties;
    private final RestTemplate restTemplate;
    private final ObjectMapper objectMapper;

    public static class MeshyTaskStatus {
        public String taskId;
        public String status; // PENDING, IN_PROGRESS, SUCCEEDED, FAILED, CANCELED
        public int progress;
        public String glbUrl;
        public int consumedCredits;
        public String errorMessage;
        public int retryAfterSeconds = 5;
    }

    public static class MeshyRateLimitException extends RuntimeException {
        private final int retryAfterSeconds;

        public MeshyRateLimitException(String message, int retryAfterSeconds) {
            super(message);
            this.retryAfterSeconds = retryAfterSeconds;
        }

        public int getRetryAfterSeconds() {
            return retryAfterSeconds;
        }
    }

    @org.springframework.beans.factory.annotation.Autowired
    public MeshyClient(MeshyModel3DProperties properties) {
        this(properties, new RestTemplate());
    }

    public MeshyClient(MeshyModel3DProperties properties, RestTemplate restTemplate) {
        this.properties = properties;
        this.restTemplate = restTemplate;
        this.objectMapper = new ObjectMapper();
    }

    public RestTemplate getRestTemplate() {
        return restTemplate;
    }

    /**
     * Submits an Image-to-3D generation task to Meshy OpenAPI v1
     *
     * @param imageBase64DataUri Base64 data URI (data:image/png;base64,...)
     * @return Task ID generated by Meshy
     */
    public String createImageTo3DTask(String imageBase64DataUri) {
        String apiKey = properties.getApiKey();
        if (apiKey == null || apiKey.isBlank()) {
            throw new IllegalStateException("MESHY_API_KEY environment variable is not configured.");
        }

        String url = properties.getBaseUrl() + "/image-to-3d";

        HttpHeaders headers = new HttpHeaders();
        headers.setContentType(MediaType.APPLICATION_JSON);
        headers.setBearerAuth(apiKey);

        ObjectNode payload = objectMapper.createObjectNode();
        payload.put("image_url", imageBase64DataUri);
        payload.put("ai_model", properties.getAiModel());
        payload.put("topology", properties.getTopology());
        payload.put("target_polycount", properties.getTargetPolycount());
        payload.put("should_remesh", properties.isShouldRemesh());
        payload.put("should_texture", properties.isShouldTexture());
        payload.put("enable_pbr", properties.isEnablePbr());
        payload.put("image_enhancement", properties.isImageEnhancement());

        ArrayNode formats = payload.putArray("target_formats");
        formats.add("glb");

        HttpEntity<String> requestEntity = new HttpEntity<>(payload.toString(), headers);

        try {
            log.info("Sending Meshy Image-to-3D creation request (ai_model={}, polycount={})",
                    properties.getAiModel(), properties.getTargetPolycount());
            ResponseEntity<String> response = restTemplate.postForEntity(url, requestEntity, String.class);

            if (response.getStatusCode().is2xxSuccessful() && response.getBody() != null) {
                JsonNode root = objectMapper.readTree(response.getBody());
                if (root.has("result")) {
                    return root.get("result").asText();
                } else if (root.has("id")) {
                    return root.get("id").asText();
                }
            }
            throw new IllegalStateException("Unexpected response format from Meshy API: " + response.getBody());
        } catch (HttpClientErrorException e) {
            if (e.getStatusCode() == HttpStatus.BAD_REQUEST) {
                log.error("Meshy 400 Bad Request: {}", e.getResponseBodyAsString());
                String msg = extractErrorMessage(e.getResponseBodyAsString(), "Invalid generation parameters submitted to Meshy.");
                throw new IllegalArgumentException(msg, e);
            } else if (e.getStatusCode() == HttpStatus.UNAUTHORIZED) {
                log.error("Meshy 401 Unauthorized: Invalid API key configuration.");
                throw new IllegalStateException("Server configuration error: Meshy API authentication failed.", e);
            } else if (e.getStatusCode() == HttpStatus.PAYMENT_REQUIRED) {
                log.error("Meshy 402 Payment Required: Credit limit reached.");
                throw new IllegalStateException("Meshy AI credits exhausted or active subscription required. Contact system administrator.", e);
            } else if (e.getStatusCode() == HttpStatus.TOO_MANY_REQUESTS) {
                int retrySec = extractRetryAfter(e.getResponseHeaders());
                log.warn("Meshy 429 Rate Limit hit. Retry-After: {}s", retrySec);
                throw new MeshyRateLimitException("Meshy rate limit exceeded. Please retry in " + retrySec + " seconds.", retrySec);
            }
            throw new RuntimeException("Meshy API returned client error: " + e.getStatusCode(), e);
        } catch (ResourceAccessException e) {
            log.warn("Meshy network timeout / connection error: {}", e.getMessage());
            throw new RuntimeException("Meshy service network timeout. Generation task queued for retry.", e);
        } catch (Exception e) {
            log.error("Meshy API communication failed: {}", e.getMessage(), e);
            throw new RuntimeException("Failed to initiate 3D model with Meshy: " + e.getMessage(), e);
        }
    }

    /**
     * Polls the status and progress of an existing Meshy task
     */
    public MeshyTaskStatus pollTaskStatus(String taskId) {
        String apiKey = properties.getApiKey();
        String url = properties.getBaseUrl() + "/image-to-3d/" + taskId;

        HttpHeaders headers = new HttpHeaders();
        headers.setBearerAuth(apiKey);
        HttpEntity<Void> requestEntity = new HttpEntity<>(headers);

        try {
            ResponseEntity<String> response = restTemplate.exchange(url, HttpMethod.GET, requestEntity, String.class);
            MeshyTaskStatus status = new MeshyTaskStatus();
            status.taskId = taskId;

            if (response.getStatusCode().is2xxSuccessful() && response.getBody() != null) {
                JsonNode root = objectMapper.readTree(response.getBody());

                status.status = root.has("status") ? root.get("status").asText().toUpperCase() : "IN_PROGRESS";
                status.progress = root.has("progress") ? root.get("progress").asInt() : 0;
                status.consumedCredits = root.has("consumed_credits") ? root.get("consumed_credits").asInt() : 0;

                if (root.has("model_urls") && root.get("model_urls").has("glb")) {
                    status.glbUrl = root.get("model_urls").get("glb").asText();
                }

                if (root.has("task_error") && !root.get("task_error").isNull()) {
                    JsonNode errNode = root.get("task_error");
                    status.errorMessage = errNode.has("message") ? errNode.get("message").asText() : errNode.asText();
                }

                status.retryAfterSeconds = extractRetryAfter(response.getHeaders());
                return status;
            }

            throw new IllegalStateException("Failed to retrieve task status from Meshy: " + response.getBody());
        } catch (HttpClientErrorException.TooManyRequests e) {
            int retrySec = extractRetryAfter(e.getResponseHeaders());
            throw new MeshyRateLimitException("Rate limit while polling task. Retry after " + retrySec + " seconds.", retrySec);
        } catch (HttpClientErrorException.NotFound e) {
            throw new IllegalArgumentException("Meshy task ID not found: " + taskId, e);
        } catch (Exception e) {
            log.warn("Error polling Meshy task {}: {}", taskId, e.getMessage());
            throw new RuntimeException("Error polling Meshy task status: " + e.getMessage(), e);
        }
    }

    /**
     * Downloads raw GLB model binary from Meshy signed URL
     */
    public byte[] downloadGlb(String glbUrl) {
        log.info("Downloading generated GLB from Meshy signed URL...");
        byte[] bytes = restTemplate.getForObject(glbUrl, byte[].class);
        if (bytes == null || bytes.length == 0) {
            throw new IllegalStateException("Downloaded GLB model is empty.");
        }
        return bytes;
    }

    /**
     * Fetches current account credit balance from /balance
     */
    public int getAccountBalance() {
        String apiKey = properties.getApiKey();
        if (apiKey == null || apiKey.isBlank()) return 0;

        String url = properties.getBaseUrl() + "/balance";
        HttpHeaders headers = new HttpHeaders();
        headers.setBearerAuth(apiKey);
        HttpEntity<Void> requestEntity = new HttpEntity<>(headers);

        try {
            ResponseEntity<String> response = restTemplate.exchange(url, HttpMethod.GET, requestEntity, String.class);
            if (response.getStatusCode().is2xxSuccessful() && response.getBody() != null) {
                JsonNode root = objectMapper.readTree(response.getBody());
                if (root.has("balance")) {
                    return root.get("balance").asInt();
                }
            }
        } catch (Exception e) {
            log.warn("Could not query Meshy balance: {}", e.getMessage());
        }
        return -1;
    }

    private int extractRetryAfter(HttpHeaders headers) {
        if (headers != null && headers.getFirst("Retry-After") != null) {
            try {
                String val = headers.getFirst("Retry-After");
                if (val != null) return Integer.parseInt(val.trim());
            } catch (Exception ignored) {
            }
        }
        return 5;
    }

    private String extractErrorMessage(String body, String defaultMsg) {
        try {
            JsonNode root = objectMapper.readTree(body);
            if (root.has("message")) return root.get("message").asText();
            if (root.has("error")) return root.get("error").asText();
        } catch (Exception ignored) {
        }
        return defaultMsg;
    }
}
